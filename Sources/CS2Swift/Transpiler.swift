/// Translates C# files to Swift.
public enum Transpiler {
    /// A source file's path, as it should appear in diagnostics and headers, and its text.
    public typealias Source = (path: String, text: String)

    /// What a run produced.
    public struct Result: Sendable {
        /// Each translated file: the output name (`ButtonRow.swift`) and its Swift.
        public var files: [(name: String, swift: String)] = []
        /// Files that couldn't be translated, and why. Nothing is written for them.
        public var errors: [(path: String, error: TranspileError)] = []
        /// Translations to check by hand.
        public var warnings: [(path: String, warning: Warning)] = []
    }

    /// The name of the support file every translation needs beside it.
    public static let supportFileName = "CSharpSupport.swift"

    /// Translates `sources`. `references` are read only for what they declare (types,
    /// members, signatures), so calls into code that isn't being translated still get the
    /// right conversions; a reference that can't be read is skipped with a warning.
    public static func transpile(_ sources: [Source], references: [Source] = []) -> Result {
        var result = Result()
        var parsed: [SourceFile] = []
        for source in sources {
            do {
                var parser = try Parser(source: source.text, path: source.path)
                parsed.append(try parser.parseFile())
            } catch {
                result.errors.append((source.path, error))
            }
        }
        var referenced: [SourceFile] = []
        for reference in references {
            do {
                var parser = try Parser(source: reference.text, path: reference.path)
                referenced.append(try parser.parseFile())
            } catch {
                result.warnings.append((reference.path, Warning(location: error.location, message: "skipped as a reference: \(error.message)")))
            }
        }

        let symbols = SymbolTable(files: referenced + parsed)
        for file in parsed {
            let emitter = Emitter(symbols: symbols)
            let header = "// Generated by cs2swift from \(file.path). Don't edit; change the C# and run cs2swift again.\n\n"
            do {
                let swift = try emitter.emit(file, header: header)
                let base = file.path.split(separator: "/").last.map(String.init) ?? file.path
                let name = (base.hasSuffix(".cs") ? String(base.dropLast(3)) : base) + ".swift"
                result.files.append((name, swift))
            } catch {
                result.errors.append((file.path, error))
            }
            result.warnings.append(contentsOf: emitter.warnings.map { (file.path, $0) })
        }
        return result
    }

    /// The support file's Swift: what the translations call that neither Swift nor
    /// raylib-swift has.
    public static let supportSource = """
    // Generated by cs2swift: support for the Swift it translates from C#. Don't edit.

    extension Int {
        /// C#'s `(int)` cast of a `float`, as .NET 9 and later do it: toward zero, saturating at
        /// `Int32`'s bounds, and 0 for NaN, where Swift's `Int(_:)` would trap.
        init(saturating value: Float) {
            self.init(saturating: Double(value))
        }

        /// C#'s `(int)` cast of a `double`; see `init(saturating:)` for `Float`.
        init(saturating value: Double) {
            if value.isNaN {
                self = 0
            } else if value >= Double(Int32.max) {
                self = Int(Int32.max)
            } else if value <= Double(Int32.min) {
                self = Int(Int32.min)
            } else {
                self = Int(value)
            }
        }
    }

    extension Character {
        /// C#'s `(char)` cast of an integer: that UTF-16 code unit, or U+FFFD when it isn't a
        /// character on its own (half of a surrogate pair, or out of range).
        init(utf16 code: some BinaryInteger) {
            if let unit = UInt16(exactly: code), let scalar = Unicode.Scalar(unit) {
                self = Character(scalar)
            } else {
                self = "\\u{FFFD}"
            }
        }

        /// C#'s `(int)` cast of a `char`: its UTF-16 code unit (the first, for a character
        /// that needs two).
        var utf16Code: Int {
            Int(utf16.first ?? 0)
        }
    }

    /// C#'s `Math.Clamp`, except that a low bound above the high one gives the high bound,
    /// where C# throws.
    func clamp<T: Comparable>(_ value: T, _ low: T, _ high: T) -> T {
        min(max(value, low), high)
    }

    /// A copy of a value with some fields changed, for C#'s `with` expressions.
    func with<T>(_ value: T, _ change: (inout T) -> Void) -> T {
        var copy = value
        change(&copy)
        return copy
    }

    """
}
